    /**
     * Indicate that the comic is featured.
     */
    public function featured(): static
    {
        return $this->state(function (array $attributes) {
            return [
                'is_featured' => true,
                'status' => 'published',
                'published_at' => $this->faker->dateTimeBetween('-6 months', 'now'),
            ];
        });
    }

    /**
     * Indicate that the comic is published.
     */
